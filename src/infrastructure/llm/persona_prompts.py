def build_system_prompt(
    persona: PersonaType,
    quant_context_markdown: Optional[str] = None,
    user_profile_markdown: Optional[str] = None
) -> str:
    """
    Constructs complete system prompt for LLM incorporating persona prompt,
    real quantum data context (Zero-Hallucination RAG), user memory profile, and mandatory formatting rules.
    """
    base_prompt = SYSTEM_PROMPTS.get(persona, SYSTEM_PROMPTS[PersonaType.QUANT])
    
    rules = """
КРИТИЧЕСКИЕ ПРАВИЛА ГЕНЕРАЦИИ ОТВЕТА (ZERO-HALLUCINATION PROTOCOL):
1. Опирайся на реальные данные MaBuy (цены, стопы, тейки, риски). Никаких галлюцинаций.
2. Соблюдай выбранный характер и тональность (Квант, Дзен, Цундере, Яндере), но БЕЗ перегруза и фальши.
3. ПИШИ ЛАКОНИЧНО, ЧИСТО И ПО ДЕЛУ (стиль Telegram Premium / Apple): никакого визуального мусора, гигантских простыней текста, лишних технических статусов вроде `[▪_▪]` и бесконечных повторений.
4. Твой ответ должен приятно и легко читаться с экрана смартфона за 15-20 секунд (2–3 емких, живых и полезных абзаца).
5. Не вставляй никаких юридических дисклеймеров, технических тегов и служебных логов — только чистый, красивый ответ.
"""

    profile_section = ""
    if user_profile_markdown:
        profile_section = f"""
================================================================================
ДОЛГОВРЕМЕННАЯ ПАМЯТЬ И АДАПТИВНЫЙ ПРОФИЛЬ ТРЕЙДЕРА:
{user_profile_markdown}
================================================================================
"""

    context_section = ""
    if quant_context_markdown:
        context_section = f"""
================================================================================
ЖИВОЙ КВАНТОВЫЙ КОНТЕКСТ ПЛАТФОРМЫ MABUY (РЕАЛЬНЫЕ ДАННЫЕ):
{quant_context_markdown}
================================================================================
"""

    return f"{base_prompt}\n{rules}\n{profile_section}\n{context_section}".strip()
